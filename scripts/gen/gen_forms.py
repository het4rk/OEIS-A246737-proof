import pickle, sympy as sp
from model import K
F=pickle.load(open('forms.pkl','rb'))
NS='A246737'
def pc(c): return str(sp.expand(c)).replace('**','^').replace('K','k')
def block(tag,G,kint,e,kexpr):
    out=[]
    karg="(k : ℤ) " if not kint else ""
    kapp=" (k : ℤ)" if not kint else ""
    epsarg = "{k : ℕ} (he : eps k = %d)"%e if not kint else "(he : eps %s = %d)"%(kexpr,e)
    for i,g in enumerate(G):
        terms=[f"({pc(c)}) * v.t{j}" for j,c in enumerate(g) if c!=0] or ["0"]
        out.append(f"/-- `lv0 ∘ step^{i}` as an explicit linear form -/\ndef {tag}{i} {karg}(v : St) : ℤ :=\n  "+" +\n    ".join(terms)+"\n")
    out.append(f"lemma {tag}_base {epsarg} (v : St) : lv0 {kexpr} v = {tag}0{kapp} v := by\n  unfold lv0 {tag}0; (try rw [he]); push_cast; ring\n")
    for i in range(len(G)-1):
        out.append(f"lemma {tag}_chain{i} {epsarg} (v : St) :\n    {tag}{i}{kapp} (step {kexpr} v) = {tag}{i+1}{kapp} v := by\n  unfold {tag}{i} {tag}{i+1} step; simp only; (try rw [he]); push_cast; ring\n")
    return "\n".join(out)
hdr=lambda imp,doc: f"import {NS}.{imp}\n\n/-!\n# {doc} (generated by `gen/gen_forms.py`)\n-/\n\nset_option maxHeartbeats 4000000\nset_option maxRecDepth 200000\n\nnamespace {NS}\n\n"
G,c=F[0]; open(f'/workspace/oeis-6/{NS}/{NS}/FormsOdd.lean','w').write(hdr('Step','Linear forms for odd k')+block('Go',G,False,0,'k')+f"\nend {NS}\n")
G,c=F[1]; open(f'/workspace/oeis-6/{NS}/{NS}/FormsEven.lean','w').write(hdr('Step','Linear forms for even k')+block('Ge',G,False,1,'k')+f"\nend {NS}\n")
s=hdr('Step','Linear forms for k = 1..6')
for kk in [1,2,3,4,5,6]:
    G,c=F[('k',kk)]; s+=block(f'G{kk}_',G,True,1-kk%2,str(kk))+"\n"
open(f'/workspace/oeis-6/{NS}/{NS}/FormsSmall.lean','w').write(s+f"\nend {NS}\n")
print({k:(len(v[0]),[str(x) for x in v[1]]) for k,v in F.items() if not isinstance(k,int)})
