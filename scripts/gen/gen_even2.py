# Even-k forms via coefficient vectors: chain lemmas reduce to univariate polynomial identities.
import pickle, re, sympy as sp
from model import K
NS='A246737'
F=pickle.load(open('forms.pkl','rb')); G,c=F[1]; d=len(c); N=35
k=sp.Symbol('k')
def evs(x):
    p=sp.Poly(sp.expand(sp.sympify(x).subs(K,k)),k)
    cs=[int(c) for c in reversed(p.all_coeffs())] if not p.is_zero else []
    while cs and cs[-1]==0: cs.pop()
    return 'ev ['+', '.join(map(str,cs))+'] k'
def pc(x): return str(sp.expand(sp.sympify(x).subs(K,k))).replace('**','^')
# parse step matrix from StepGen.lean with eps=1
src=open(f'/workspace/oeis-6/{NS}/{NS}/StepGen.lean').read()
A=[[0]*N for _ in range(N)]
for i,line in re.findall(r'\n  t(\d+) := (.*)',src):
    for coef,j in re.findall(r'\(([^()]*(?:\([^()]*\)[^()]*)*)\) \* s\.t(\d+)',line):
        e=coef.replace('(eps k : ℤ)','1').replace('(k : ℤ)','k').replace('^','**')
        A[int(i)][int(j)]=sp.sympify(e,locals={'k':k})
# sanity: pull of G[i] equals G[i+1]
for i in range(d):
    for j in range(N):
        s=sum(sp.sympify(G[i][l]).subs(K,k)*A[l][j] for l in range(N))
        assert sp.expand(s-sp.sympify(G[i+1][j]).subs(K,k))==0,(i,j)
for j in range(N):
    s=sp.sympify(G[d][j])-sum(sp.sympify(c[t])*sp.sympify(G[d-1-t][j]) for t in range(d))
    assert sp.expand(s)==0
cs=lambda name: " + ".join(f"{name} {i} * v.t{i}" for i in range(N))
o=[f"import {NS}.Step\n\n/-!\n# Linear forms for even k (generated by `gen/gen_even2.py`)\n\nEach form `Ge i` is `lin (ge i k)` for an explicit coefficient vector; one step of the\nrecursion acts on coefficient vectors by `pull`, so every chain lemma reduces to 35\nunivariate polynomial identities in `k`.\n-/\n\nset_option maxHeartbeats 4000000\nset_option maxRecDepth 200000\n\nnamespace {NS}\n"]
o.append("/-- Horner evaluation of a coefficient list (constant term first) -/\ndef ev : List ℤ → ℤ → ℤ\n  | [], _ => 0\n  | a :: l, k => a + k * ev l k\n")
o.append(f"/-- the linear form with coefficient vector `c` (stored as an `St`) -/\ndef lin (c : St) (v : St) : ℤ :=\n  "+" + ".join(f"c.t{i} * v.t{i}" for i in range(N))+"\n")
o.append("/-- componentwise sum -/\ndef addS (a b : St) : St :=\n  ⟨"+", ".join(f"a.t{i} + b.t{i}" for i in range(N))+"⟩\n")
o.append("/-- scalar multiple -/\ndef smulS (x : ℤ) (a : St) : St :=\n  ⟨"+", ".join(f"x * a.t{i}" for i in range(N))+"⟩\n")
o.append("lemma lin_add (c d v : St) : lin (addS c d) v = lin c v + lin d v := by\n  unfold lin addS; ring\n")
o.append("lemma lin_smul (a : ℤ) (c v : St) : lin (smulS a c) v = a * lin c v := by\n  unfold lin smulS; ring\n")
rows=[]
for j in range(N):
    t=[f"({pc(A[l][j])}) * c.t{l}" for l in range(N) if A[l][j]!=0]
    rows.append(" + ".join(t) or "0")
o.append(f"/-- the action of `step` (for `eps k = 1`) on coefficient vectors -/\ndef pull (k : ℤ) (c : St) : St :=\n  ⟨" + ",\n    ".join(rows) + "⟩\n")
o.append("lemma lin_step {k : ℕ} (he : eps k = 1) (c v : St) :\n    lin c (step k v) = lin (pull (k : ℤ) c) v := by\n  unfold lin pull step; dsimp only; rw [he]; push_cast; ring\n")
for i in range(d+1):
    o.append(f"/-- coefficient vector of `lv0 ∘ step^{i}` -/\ndef ge{i} (k : ℤ) : St :=\n  ⟨" + ",\n    ".join(evs(x) for x in G[i]) + "⟩\n")
    o.append(f"/-- `lv0 ∘ step^{i}` as a linear form -/\ndef Ge{i} (k : ℤ) (v : St) : ℤ := lin (ge{i} k) v\n")
o.append("lemma Ge_base {k : ℕ} (he : eps k = 1) (v : St) : lv0 k v = Ge0 (k : ℤ) v := by\n  unfold lv0 Ge0 lin ge0; simp only [ev]; rw [he]; push_cast; ring\n")
for i in range(d):
    o.append(f"lemma ge_pull{i} (k : ℤ) : pull k (ge{i} k) = ge{i+1} k := by\n  ext <;> simp only [pull, ge{i}, ge{i+1}, ev] <;> ring\n")
    o.append(f"lemma Ge_chain{i} {{k : ℕ}} (he : eps k = 1) (v : St) :\n    Ge{i} (k : ℤ) (step k v) = Ge{i+1} (k : ℤ) v := by\n  unfold Ge{i} Ge{i+1}; rw [lin_step he, ge_pull{i}]\n")
terms=[f"(smulS ({pc(c[t])}) (ge{d-1-t} k))" for t in range(d) if c[t]!=0]
comb=terms[-1]
for t in reversed(terms[:-1]): comb=f"(addS {t} {comb})"
o.append(f"lemma ge_rec (k : ℤ) : ge{d} k = {comb} := by\n  ext <;> simp only [ev, addS, smulS, ge{d}, "+", ".join(f"ge{i}" for i in range(d))+"] <;> ring\n")
combG=" + ".join(f"({pc(c[t])}) * Ge{d-1-t} k v" for t in range(d) if c[t]!=0)
o.append(f"lemma Ge_rec (k : ℤ) (v : St) : Ge{d} k v = {combG} := by\n  simp only ["+", ".join(f"Ge{i}" for i in range(d+1))+f"]\n  rw [ge_rec]; simp only [lin_add, lin_smul]; ring\n")
o.append(f"end {NS}\n")
open(f'/workspace/oeis-6/{NS}/{NS}/FormsEven.lean','w').write("\n".join(o))
print("ok")
