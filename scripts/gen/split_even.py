# split the generated FormsEven.lean into cacheable modules
import re
P='/workspace/oeis-6/A246737/A246737/'
s=open(P+'FormsEven.lean').read()
hdr_end=s.index('namespace A246737')+len('namespace A246737\n')
body=s[hdr_end:s.rindex('end A246737')]
a=body.index('lemma ge_pull0'); r=body.index('lemma ge_rec')
parts=[p for p in re.split(r'(?=lemma ge_pull\d+ )',body[a:r]) if p.strip()]
H=lambda imp:f"import A246737.{imp}\n\n/-! Even-k chain lemmas (generated by `gen/gen_even2.py`, split by `gen/split_even.py`) -/\n\nset_option maxHeartbeats 4000000\nset_option maxRecDepth 200000\n\nnamespace A246737\n\n"
open(P+'EvenBase.lean','w').write(s[:hdr_end]+body[:a]+'end A246737\n')
prev='EvenBase'
for g in range(5):
    n=f'EvenChain{g}'; open(P+n+'.lean','w').write(H(prev)+''.join(parts[g*5:(g+1)*5])+'end A246737\n'); prev=n
open(P+'FormsEven.lean','w').write(H(prev)+body[r:]+'end A246737\n')
